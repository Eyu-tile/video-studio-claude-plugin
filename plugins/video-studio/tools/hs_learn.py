#!/usr/bin/env python3
"""Learn a brand's ad history from saved Hyperscale briefs (used by `vs hyperscale learn`).

Reads every <number>.json (a get_brief result) in a folder and writes, next to it:
  briefs_index.json   one row per brief: stage, pod, people, angle, awareness, type, format, hooks, uploads, rounds
  CATALOGUE.md        every brief by stage, with its hypothesis line
  HOOK_BANK.md        every hook (spoken line + on-screen/visual), by angle, launched and approved first
  WINNER_SIGNALS.md   every performance figure the briefs quote about other ads (#107 "$28.2k spent"...), by ad
  REVIEW_NOTES.md     every review note (changes requested) with brief, round and time
  EDITING_RULES.md    the editing notes teams repeat (music, captions, b-roll, voice) with counts, and the
                      long-form house rules with the briefs that state them
  STATS.md            counts: angle x stage, format x stage, video type x stage, awareness, pod output
Numbers come only from the briefs' own text; nothing here is Meta data.
"""
import collections
import json
import re
from pathlib import Path

DONE = ("Launched", "Approved")
FIG = re.compile(r"(\$\s?\d[\d,.]*\s?[kKmM]?(?:\s?(?:spent|spend|in spend))?|\d+(?:\.\d+)?\s?%\s?(?:of\s+(?:last\s+week'?s\s+|the\s+)?"
                 r"spend|hook rate|ctr|thumb-?stop|hold rate)?|roas\s*(?:of\s*)?\d+(?:\.\d+)?|\d+(?:\.\d+)?\s?roas|"
                 r"\d+(?:\.\d+)?x\s?roas|cpa\s*\$?\d+(?:\.\d+)?)", re.I)
REF = re.compile(r"#(\d{2,4})\b")
WIN = re.compile(r"\bwinn(er|ers|ing)\b|\bproven\b|\bscal(ing|ed|e)\b|\bbest\b|\btop\b|our .{0,20}#\d", re.I)
PRAISE = re.compile(r"great|killed|love|nice|perfect|amazing|awesome|good job|well done|fire|🔥|💯|beautiful|clean", re.I)
FIXWORD = re.compile(r"\b(but|change|fix|remove|missing|wrong|instead|should|need|please|too|don't|not)\b", re.I)


def text_of(b):
    rows = b.get("script") or []
    return "\n".join([b.get("idea") or "", *(b.get("editing_notes") or []),
                      *(" ".join(str(r.get(k) or "") for k in ("script", "visual", "on_screen_text")) for r in rows)])


def first_line(s, n=150):
    s = re.sub(r"\s+", " ", (s or "").strip())
    m = re.match(r"(?:hypothesis:\s*)?(.+?[.!?])(\s|$)", s, re.I)
    s = m.group(1) if m else s
    return s[:n] + ("..." if len(s) > n else "")


def load(folder):
    out = []
    for f in sorted(Path(folder).glob("*.json"), key=lambda p: int(p.stem) if p.stem.isdigit() else 0):
        if not f.stem.isdigit():
            continue
        try:
            b = json.loads(f.read_text())
        except json.JSONDecodeError:
            continue
        if isinstance(b, dict) and "number" in b:
            out.append(b)
    return out


def index_row(b):
    txt = text_of(b)
    return {"number": b["number"], "title": b.get("title"), "stage": b.get("stage"), "round": b.get("round"),
            "pod": b.get("pod"), "editor": b.get("editor"), "strategist": b.get("strategist"),
            "angle": b.get("angle"), "awareness": b.get("awareness"), "video_type": b.get("video_type"),
            "format": b.get("format"), "hooks": len(b.get("hooks") or []), "sizes": b.get("sizes"),
            "uploads": len(b.get("ads") or []), "open_notes": len(b.get("open_notes") or []),
            "refs": sorted({int(x) for x in REF.findall(txt)} - {b["number"]}),
            "hypothesis": first_line(b.get("idea"))}


def signals(briefs):
    """{ref: [(citing brief, sentence)]} for sentences naming #ref with a figure."""
    out = collections.defaultdict(list)
    for b in briefs:
        for sent in re.split(r"(?<=[.;\n])\s+", text_of(b)):
            refs = REF.findall(sent)
            if refs and (FIG.search(sent) or WIN.search(sent)):
                for r in set(refs):
                    if int(r) != b["number"]:
                        out[int(r)].append((b["number"], re.sub(r"\s+", " ", sent.strip())[:300]))
    return out


def md_table(rows, cols):
    L = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        L.append("| " + " | ".join(str(x if x not in (None, "") else "-").replace("|", "/").replace("\n", " ")
                                     for x in r) + " |")
    return L


def learn(folder, brand=""):
    folder = Path(folder)
    briefs = load(folder)
    if not briefs:
        raise SystemExit(f"no <number>.json briefs in {folder}")
    by_num = {b["number"]: b for b in briefs}
    idx = [index_row(b) for b in briefs]
    (folder.parent / "briefs_index.json").write_text(json.dumps(idx, indent=1, ensure_ascii=False) + "\n")
    out = folder.parent
    head = f"# {brand or 'Brand'}: %s\n\nGenerated by `vs hyperscale learn` from {len(briefs)} Hyperscale briefs. " \
           "Edit the hand-written files (AD_PLAYBOOK.md, WINNING_ADS.md), not this one.\n"

    # catalogue
    L = [head % "brief catalogue", ""]
    order = ["Launched", "Approved", "Ready for review", "In production", "Changes requested", "Ready for edit", "Idea"]
    stages = sorted({b.get("stage") or "?" for b in briefs}, key=lambda s: order.index(s) if s in order else 99)
    for st in stages:
        rows = [r for r in idx if (r["stage"] or "?") == st]
        L += [f"## {st} ({len(rows)})", ""]
        L += md_table([(f"#{r['number']}", r["title"], r["angle"], r["awareness"], r["video_type"], r["pod"],
                        r["editor"], r["hooks"], r["hypothesis"]) for r in sorted(rows, key=lambda r: -r["number"])],
                      ["#", "format", "angle", "awareness", "type", "pod", "editor", "hooks", "hypothesis"])
        L.append("")
    dup = [b for b in briefs if (b.get("title") or "").lower() == "duplicate" and b.get("reference")]
    if dup:
        L += ["## Remakes (\"Duplicate\" briefs) and the reference ads they copy", ""]
        L += md_table([(f"#{b['number']}", b.get("stage"), b.get("angle"), b.get("awareness"), len(b.get("ads") or []),
                        b.get("reference")) for b in sorted(dup, key=lambda b: -b["number"])],
                      ["#", "stage", "angle", "awareness", "uploads", "reference"])
        L.append("")
    (out / "CATALOGUE.md").write_text("\n".join(L) + "\n")

    # hook bank
    L = [head % "hook bank", "", "Spoken line, then the on-screen text or visual. Launched and approved briefs first.", ""]
    angles = collections.defaultdict(list)
    for b in sorted(briefs, key=lambda b: (b.get("stage") not in DONE, -b["number"])):
        for r in b.get("script") or []:
            if (r.get("module") or "").lower() != "hook":
                continue
            say = re.sub(r"^same voiceover as h\d+:?\s*", "", str(r.get("script") or "").strip(), flags=re.I)
            see = str(r.get("on_screen_text") or "").strip() or str(r.get("visual") or "").strip()
            angles[b.get("angle") or "Other"].append((b, say, see))
    n = 0
    for ang in sorted(angles, key=lambda a: -len(angles[a])):
        L += [f"## {ang} ({len(angles[ang])})", ""]
        for b, say, see in angles[ang]:
            n += 1
            L.append(f"- **#{b['number']}** {b.get('stage')} · {b.get('video_type') or b.get('title')} · "
                     f"{b.get('awareness')}  \n  say: {first_line(say, 220) or '-'}  \n  show: {first_line(see, 220) or '-'}")
        L.append("")
    L.insert(2, f"{n} hooks.\n")
    (out / "HOOK_BANK.md").write_text("\n".join(L) + "\n")

    # winner signals
    sig = signals(briefs)
    L = [head % "winner signals", "",
         "Every sentence in a brief that names another ad (#number) with a figure or a word like winner, proven, "
         "scaling or best. These are the "
         "strategists' own numbers, not Meta exports: check them in Analytics before relying on them.", ""]
    for ref in sorted(sig, key=lambda r: -len(sig[r])):
        rb = by_num.get(ref)
        desc = f"{rb.get('title')} · {rb.get('angle')} · {rb.get('video_type')} · {rb.get('stage')}" if rb else \
            "(brief not saved)"
        L += [f"## #{ref}: {desc}", f"cited {len(sig[ref])}x", ""]
        seen = set()
        for cb, s in sig[ref]:
            if s not in seen:
                seen.add(s)
                L.append(f"- in #{cb}: {s}")
        L.append("")
    (out / "WINNER_SIGNALS.md").write_text("\n".join(L) + "\n")

    # review notes
    L = [head % "review notes", "", "Changes requested by strategists, as written on the brief.", ""]
    k = 0
    groups = {"Corrections (what to fix, and not repeat)": [], "Praise (what to keep doing)": []}
    for b in sorted(briefs, key=lambda b: -b["number"]):
        for nt in b.get("open_notes") or []:
            k += 1
            note = re.sub(r"\s+", " ", str(nt.get("note") or "")).strip()
            praise = PRAISE.search(note) and not FIXWORD.search(note)
            groups["Praise (what to keep doing)" if praise else "Corrections (what to fix, and not repeat)"].append(
                f"- #{b['number']} ({b.get('stage')}, round {b.get('round')}, {b.get('video_type') or b.get('title')}, "
                f"editor {b.get('editor')}) {nt.get('at') or '--'}: {note}")
    for g, items in groups.items():
        if items:
            L += [f"## {g} ({len(items)})", "", *items, ""]
    if not k:
        L.append("(no open notes on these briefs; notes are cleared once a brief moves on)")
    rounds = sorted((r for r in idx if (r["round"] or 0) >= 3), key=lambda r: -(r["round"] or 0))
    if rounds:
        L += ["", "## Briefs that needed 3+ rounds", ""]
        L += md_table([(f"#{r['number']}", r["round"], r["title"], r["video_type"], r["editor"], r["stage"])
                       for r in rounds], ["#", "rounds", "format", "type", "editor", "stage"])
    (out / "REVIEW_NOTES.md").write_text("\n".join(L) + "\n")

    # editing rules
    short = collections.Counter()
    longr = collections.defaultdict(list)
    for b in briefs:
        for nt in b.get("editing_notes") or []:
            nt = nt.strip()
            if len(nt) <= 60 and ":" in nt:
                short[nt] += 1
            else:
                for para in re.split(r"\n\s*\n", nt):
                    m = re.match(r"([A-Z][A-Z &/'-]{3,40}):", para.strip())
                    if m and not para.startswith(("Avatar:", "Voiceover:")):
                        longr[m.group(1).strip()].append((b["number"], first_line(para, 300)))
    L = [head % "editing rules", "", "## Short settings (how often teams ask for each)", ""]
    by_key = collections.defaultdict(list)
    for nt, c in short.items():
        key, _, val = nt.partition(":")
        by_key[key.strip()].append((val.strip(), c))
    for key in sorted(by_key, key=lambda k: -sum(c for _, c in by_key[k])):
        L.append(f"- **{key}**: " + ", ".join(f"{v} ({c})" for v, c in sorted(by_key[key], key=lambda x: -x[1])))
    L += ["", "## House rules written into briefs", ""]
    for key in sorted(longr, key=lambda k: -len(longr[k])):
        L.append(f"### {key} ({len(longr[key])} briefs)")
        seen = set()
        for num, s in longr[key][:6]:
            if s not in seen:
                seen.add(s)
                L.append(f"- #{num}: {s}")
        L.append("")
    (out / "EDITING_RULES.md").write_text("\n".join(L) + "\n")

    # stats
    L = [head % "stats", ""]
    for field in ("angle", "title", "video_type", "awareness", "pod"):
        cnt = collections.defaultdict(collections.Counter)
        for r in idx:
            cnt[r[field] or "-"][r["stage"] if r["stage"] in DONE else "other"] += 1
        L += [f"## {field.replace('title', 'format')}", ""]
        L += md_table([(k, c["Launched"], c["Approved"], c["other"], sum(c.values()))
                       for k, c in sorted(cnt.items(), key=lambda kv: -sum(kv[1].values()))],
                      [field, "launched", "approved", "other", "total"])
        L.append("")
    eds = collections.Counter(r["editor"] for r in idx if r["stage"] in DONE)
    L += ["## Launched/approved by editor", "", ", ".join(f"{e} {c}" for e, c in eds.most_common()), ""]
    (out / "STATS.md").write_text("\n".join(L) + "\n")
    return {"briefs": len(briefs), "hooks": n, "winner_refs": len(sig), "notes": k,
            "files": ["briefs_index.json", "CATALOGUE.md", "HOOK_BANK.md", "WINNER_SIGNALS.md", "REVIEW_NOTES.md",
                      "EDITING_RULES.md", "STATS.md"]}
